# Pad to 64 cards (512 bytes)
while len(gram_bytes) < 512:
    gram_bytes.append(0)

# IntelliVision color palette (approximate RGB for display)
# Using tan/brown for foreground, dark for background
FG_COLOR = (200, 160, 40)  # Tan/gold - IntelliVision color #3
BG_COLOR = (10, 10, 20)    # Dark background
GRID_COLOR = (40, 40, 60)

ZOOM = 6
CARD_W = 8 * ZOOM
CARD_H = 8 * ZOOM
GAP = 1 * ZOOM
LABEL_H = 14

COLS = 8
ROWS = 8

img_w = COLS * CARD_W + (COLS + 1) * GAP
img_h = ROWS * (CARD_H + LABEL_H) + (ROWS + 1) * GAP

img = Image.new('RGBA', (img_w, img_h), GRID_COLOR + (255,))
draw = ImageDraw.Draw(img)

def draw_card(draw, x0, y0, card_num):
    """Draw one 8x8 card at position with zoom"""
    base = card_num * 8
    data = gram_bytes[base:base+8]
    
    for row in range(8):
        byte = data[row]
        for col in range(8):
            bit = (byte >> (7 - col)) & 1
            color = FG_COLOR + (255,) if bit else BG_COLOR + (255,)
            px = x0 + col * ZOOM
            py = y0 + row * ZOOM
            draw.rectangle([px, py, px + ZOOM - 1, py + ZOOM - 1], fill=color)

# Try to use a basic font
try:
    from PIL import ImageFont
    font = ImageFont.truetype("arial.ttf", 10)
except:
    font = ImageFont.load_default()

for card_num in range(64):
    row = card_num // COLS
    col = card_num % COLS
    x0 = GAP + col * (CARD_W + GAP)
    y0 = GAP + row * (CARD_H + LABEL_H + GAP)
    
    draw_card(draw, x0, y0, card_num)
    
    # Label
    label = f"${card_num:02X}"
    label_y = y0 + CARD_H + 2
    # Simple text via draw
    draw.text((x0 + 2, label_y), label, fill=(200, 200, 200, 255), font=font)

# Also print ASCII representation of each card
print("=== ALL GRAM CARDS (ASCII) ===\n")
for card_num in range(64):
    base = card_num * 8
    data = gram_bytes[base:base+8]
    has_data = any(b != 0 for b in data)
    if not has_data and card_num > 40:
        continue
    
    print(f"Card ${card_num:02X} (${0x3800 + card_num*8:04X}):")
    for row in range(8):
        byte = data[row]
        line = ''
        for col in range(8):
            bit = (byte >> (7 - col)) & 1
            line += '##' if bit else '..'
        print(f"  {line}")
    print()

