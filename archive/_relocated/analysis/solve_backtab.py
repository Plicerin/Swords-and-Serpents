distinct = sorted(set(backtab_raw))

# Formula: BT = ((A_lo << 8) ^ A) & 0x3607) ^ (C << 3)
# where A = attr_word, A_lo = A & 0xFF, C = card_byte
#
# Let X = ((A_lo << 8) ^ A) & 0x3607
# Then BT = X ^ (C << 3)
#
# For each BT, find all (A, C) pairs that work.

print("=== Solving for attr/card pairs per BACKTAB word ===\n")

for bt in distinct:
    solutions = []
    for c in range(256):
        x_needed = bt ^ (c << 3)
        # x_needed must have bits only in 0x3607 positions
        if x_needed & ~0x3607:
            continue
        # Now find A such that ((A_lo << 8) ^ A) & 0x3607 == x_needed
        # A_lo = A & 0xFF
        # ((A & 0xFF) << 8) ^ A
        # Let L = A & 0xFF, H = (A >> 8) & 0xFF
        # ((A & 0xFF) << 8) ^ A = (L << 8) ^ (H << 8 | L) = ((L ^ H) << 8) | L
        # AND with 0x3607: keep bits 13,12,10,9,2,1,0
        # bits 13,12,10,9 come from (L^H)
        # bits 2,1,0 come from L
        # So we need: x_needed = the AND of the above
        
        # Brute force A (only need to check relevant bits)
        for a in range(0x10000):
            a_lo = a & 0xFF
            result = ((a_lo << 8) ^ a) & 0x3607
            if result == x_needed:
                solutions.append((a, c))
                if len(solutions) >= 5:
                    break
        if len(solutions) >= 5:
            break
    
    if solutions:
        fg = (bt >> 13) & 7
        bg = (bt >> 10) & 7
        gc = 'G' if (bt >> 9) & 1 else 'R'
        print(f"${bt:04X} (FG={fg} BG={bg} {gc}ROM card={bt&0x1FF:3d}):")
        for a, c in solutions[:5]:
            print(f"  attr=${a:04X} (lo=${a&0xFF:02X})  card=${c:02X} (${c:3d})")
        print()

