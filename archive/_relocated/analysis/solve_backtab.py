# Let me try yet another interpretation: maybe the card_byte is NOT from a separate table.
# Maybe it IS the low 5 bits of R1 (the tile descriptor).
# R1_in = tile_descriptor
# group = R1_in >> 5
# card = R1_in & 0x1F  (low 5 bits)
# 
# Then the card<<3 would be (R1_in & 0x1F) << 3, producing values 0, 8, 16, ... 248

print("\n\n=== Alternative: card from tile descriptor low bits ===")
print("Testing: card = (R1_in & 0x1F), shifted left 3, XOR'd with attr result\n")

rom = open('Swords and Serpents.bin', 'rb').read()
def rw(addr):
    off = (addr - 0x5000) * 2
    if off < 0 or off + 1 >= len(rom): return 0
    return (rom[off] << 8) | rom[off + 1]

# For each tile descriptor value 0..255, compute what BACKTAB word it produces
# with the ROM attr table
for group in range(8):  # first 8 groups
    attr_word = rw(0x65B7 + group)
    attr_byte = attr_word & 0xFF
    
    # attr processing
    r1 = attr_byte
    r1 >>= 2
    r1 = ((r1 & 0xFF) << 8) | (r1 >> 8)  # SWAP
    r1 ^= attr_word
    r1 &= 0x3607
    
    # Now test cards 0-31 (shifted by 3)
    matches = []
    for card in range(32):
        result = r1 ^ (card << 3)
        if result in backtab_raw:
            matches.append((card, result))
    
    if matches:
        print(f"  Group {group} (attr=${attr_word:04X}): {len(matches)} matches")
        for card, bt in matches[:8]:
            label = "WALL" if bt == 0x1603 else "DOOR" if bt == 0x081B else "FLOOR" if (bt>>10)&7==0 else ""
            print(f"    card={card:2d} (${card:02X}) -> ${bt:04X} {label}")
